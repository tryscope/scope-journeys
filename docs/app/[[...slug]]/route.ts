import { PAGES, htmlPath, installParam, pageBySlug, pageMarkdown } from "@/lib/pages";
import { htmlDocument, markdownToHtml } from "@/lib/render";

export const dynamic = "force-dynamic";

// The HTML face of a page. A path that is not a page answers 404 with the real pages listed, the
// way the sensor's own notfound rule answers a documentation URL that does not exist.
export async function GET(request: Request, context: { params: Promise<{ slug?: string[] }> }): Promise<Response> {
  const { slug = [] } = await context.params;
  const page = pageBySlug(slug.join("/"));
  const headers = { "content-type": "text/html; charset=utf-8", vary: "Accept", "cache-control": "public, max-age=60" };
  if (!page) {
    const list = PAGES.map((p) => `- [${p.title}](${htmlPath(p)}): ${p.description}`).join("\n");
    return new Response(htmlDocument({ page: null, title: "Not found", content: markdownToHtml(`# Not found\n\nThere is no page at \`${new URL(request.url).pathname}\`. The pages:\n\n${list}`) }), { status: 404, headers });
  }
  const markdown = pageMarkdown(page, installParam(new URL(request.url)));
  if (markdown === null) return new Response(htmlDocument({ page, title: page.title, content: markdownToHtml(`# ${page.title}\n\nThis page is generated by the docs build (\`npm run generate\`) and has not been generated here.`) }), { status: 503, headers });
  return new Response(htmlDocument({ page, title: page.title, content: markdownToHtml(markdown) }), { headers });
}
